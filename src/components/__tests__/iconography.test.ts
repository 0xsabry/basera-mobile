/**
 * Iconography regression guard (polish pass, docs/POLISH.md).
 *
 * The owner's core complaint was oversized, heavy decorative icons.
 * This static scan makes that treatment impossible to reintroduce:
 * it walks every .tsx under src/app and src/components and fails on
 *  - any glyph-bearing line whose literal fontSize exceeds the
 *    control token (32) — glyphs render at 16/20/24, control glyphs
 *    (voice disc) at most 32;
 *  - any literal fontSize > 26 anywhere, outside the explicit
 *    whitelist below (each entry is content or a control, never a
 *    decorative icon);
 *  - the old filled-tile glyph scaling expression (size * 0.46)
 *    outside the BrandMark logotype.
 *
 * Whitelist (file + line pattern + reason):
 *  - (tabs)/family.tsx `codeText` — the pairing CODE digits are
 *    content the user must read aloud, not an icon.
 *  - voice.tsx disc glyph line (`discTextColor`) — the microphone
 *    glyph inside the voice CONTROL surface, capped at exactly 32.
 *  - ui.tsx BrandMark `size * 0.52` — the «ب» letterform is the
 *    product logotype, not an icon; header use is 28dp.
 */
import * as fs from 'fs';
import * as path from 'path';

const SRC = path.join(__dirname, '..', '..');

function tsxFiles(dir: string): string[] {
  const out: string[] = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === '__tests__' || entry.name === 'node_modules') continue;
      out.push(...tsxFiles(full));
    } else if (entry.name.endsWith('.tsx')) {
      out.push(full);
    }
  }
  return out;
}

const FILES = [...tsxFiles(path.join(SRC, 'app')), ...tsxFiles(path.join(SRC, 'components'))];

function isWhitelisted(rel: string, line: string, value: number): boolean {
  if (rel.endsWith('(tabs)/family.tsx') && line.includes('codeText')) return true;
  // Voice control glyph: whitelisted ONLY at or below the 32dp cap.
  if (rel.endsWith('app/voice.tsx') && line.includes('discTextColor') && value <= 32) return true;
  return false;
}

describe('iconography guard: no oversized glyphs or icons', () => {
  it('scans a real file set', () => {
    expect(FILES.length).toBeGreaterThan(15);
  });

  it('no glyph line renders above the 32dp control cap', () => {
    const violations: string[] = [];
    for (const file of FILES) {
      const rel = path.relative(SRC, file);
      fs.readFileSync(file, 'utf8')
        .split('\n')
        .forEach((line, i) => {
          if (!/GLYPHS\.|glyph/.test(line)) return;
          const m = line.match(/fontSize:\s*(\d+)/);
          if (m && Number(m[1]) > 32) violations.push(`${rel}:${i + 1} fontSize ${m[1]}`);
        });
    }
    expect(violations).toEqual([]);
  });

  it('no literal fontSize above 26 outside the whitelist', () => {
    const violations: string[] = [];
    for (const file of FILES) {
      const rel = path.relative(SRC, file);
      fs.readFileSync(file, 'utf8')
        .split('\n')
        .forEach((line, i) => {
          const m = line.match(/fontSize:\s*(\d+)/);
          if (m && Number(m[1]) > 26 && !isWhitelisted(rel, line, Number(m[1]))) {
            violations.push(`${rel}:${i + 1} fontSize ${m[1]} :: ${line.trim().slice(0, 80)}`);
          }
        });
    }
    expect(violations).toEqual([]);
  });

  it('the filled-tile glyph scaling (size * 0.46) never returns', () => {
    const offenders: string[] = [];
    for (const file of FILES) {
      const rel = path.relative(SRC, file);
      if (fs.readFileSync(file, 'utf8').includes('0.46')) offenders.push(rel);
    }
    expect(offenders).toEqual([]);
  });
});

/**
 * Launcher-asset sanity (v1.1.2 branding, docs/BRANDING.md).
 *
 * The adaptive foreground MUST be a real alpha asset (a full-bleed
 * opaque foreground is what broke masking in the eye-icon set), the
 * classic icon must be opaque, and every density the adaptive XML /
 * splash theme references must exist at its exact pixel size.
 * Generated by scripts/generate-brand-icons.py — if this fails,
 * re-run the generator instead of hand-editing binaries.
 */
const REPO = path.join(SRC, '..');

function pngSize(file: string): [number, number] {
  const b = fs.readFileSync(file);
  return [b.readUInt32BE(16), b.readUInt32BE(20)];
}

function pngHasAlpha(file: string): boolean {
  const b = fs.readFileSync(file);
  // IHDR color type at byte 25: 6 = RGBA, 4 = gray+alpha.
  return b[25] === 6 || b[25] === 4;
}

function webpSize(file: string): [number, number] {
  const b = fs.readFileSync(file);
  const chunk = b.toString('ascii', 12, 16);
  if (chunk === 'VP8X') {
    return [b.readUIntLE(24, 3) + 1, b.readUIntLE(27, 3) + 1];
  }
  if (chunk === 'VP8L') {
    const bits = b.readUInt32LE(21);
    return [(bits & 0x3fff) + 1, ((bits >> 14) & 0x3fff) + 1];
  }
  if (chunk === 'VP8 ') {
    return [b.readUInt16LE(26) & 0x3fff, b.readUInt16LE(28) & 0x3fff];
  }
  throw new Error(`unknown webp chunk ${chunk} in ${file}`);
}

describe('brand assets: launcher + splash set is well-formed', () => {
  const dens: [string, number][] = [
    ['mdpi', 1],
    ['hdpi', 1.5],
    ['xhdpi', 2],
    ['xxhdpi', 3],
    ['xxxhdpi', 4],
  ];

  it('assets/icon.png is a 1024² opaque classic icon', () => {
    const f = path.join(REPO, 'assets', 'icon.png');
    expect(pngSize(f)).toEqual([1024, 1024]);
    expect(pngHasAlpha(f)).toBe(false);
  });

  it('assets/adaptive-foreground.png is 1024² WITH transparency (safe-zone art)', () => {
    const f = path.join(REPO, 'assets', 'adaptive-foreground.png');
    expect(pngSize(f)).toEqual([1024, 1024]);
    expect(pngHasAlpha(f)).toBe(true);
  });

  it('every mipmap density carries foreground/classic/round at exact sizes', () => {
    for (const [name, mult] of dens) {
      const dir = path.join(REPO, 'android', 'app', 'src', 'main', 'res', `mipmap-${name}`);
      expect(webpSize(path.join(dir, 'ic_launcher_foreground.webp'))).toEqual([108 * mult, 108 * mult]);
      expect(webpSize(path.join(dir, 'ic_launcher.webp'))).toEqual([48 * mult, 48 * mult]);
      expect(webpSize(path.join(dir, 'ic_launcher_round.webp'))).toEqual([48 * mult, 48 * mult]);
    }
  });

  it('every splash-logo density exists at its exact size', () => {
    for (const [name, mult] of dens) {
      const f = path.join(REPO, 'android', 'app', 'src', 'main', 'res', `drawable-${name}`, 'splashscreen_logo.png');
      expect(pngSize(f)).toEqual([288 * mult, 288 * mult]);
    }
  });

  it('app.json points the adaptive foreground at the dedicated alpha asset', () => {
    const appJson = JSON.parse(fs.readFileSync(path.join(REPO, 'app.json'), 'utf8'));
    expect(appJson.expo.android.adaptiveIcon.foregroundImage).toBe('./assets/adaptive-foreground.png');
    expect(appJson.expo.android.adaptiveIcon.backgroundColor).toBe('#0B3D2E');
    expect(appJson.expo.icon).toBe('./assets/icon.png');
  });
});
